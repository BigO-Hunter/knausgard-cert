#!/usr/bin/env python3
"""Emit cert/Table.lean: the kernel table of certificate/kernel_lower.bin as a tree of NAMED
definitions, read by an accessor that costs O(log n) small unfolds per read instead of copying a
209010-node literal term (measured: 12 MB per read for the flat literal).

Values are byte-identical to the table the author's kernel table holds: sha256 of
kernel_lower.bin = b80e5a8c70e4beb3b872dada426016bc97b0954c1a8a5eabaeb40fba49cded36, which is
inputs.json -> table_sha256 and the hash his build_kernel.py wrote.
"""
import struct, hashlib, sys
from pathlib import Path

PLAY = Path.home() / "bigo-campaign" / "knausgard-cert"
BIN = PLAY / "upstream" / "certificate" / "kernel_lower.bin"
SHA = "b80e5a8c70e4beb3b872dada426016bc97b0954c1a8a5eabaeb40fba49cded36"
VALS = list(struct.unpack("<209010I", BIN.read_bytes()))
N = len(VALS)
LEAF, MID = 64, 64
SPAN = LEAF * MID
HEAD = f"""-- Cert/Table.lean  (generated by tools/gen_table.py -- do not hand-edit)
-- The kernel table of the author's certificate/ (209010 entries, sha256 {SHA[:16]}...)
-- as a tree of named definitions. Straight data: kT k = kernel_lower.bin[k] for k <= 209009,
-- and 0 outside (which is also a lower bound, as in his g/getD convention).
set_option maxHeartbeats 0
namespace Cert
"""

def gen():
    out = [HEAD]
    leaves = []
    for c in range(0, N, LEAF):
        nm = f"L{c // LEAF}"
        leaves.append(nm)
        out.append(f"def {nm} : List Nat := [{', '.join(map(str, VALS[c:c + LEAF]))}]\n")
    mids = []
    for g in range(0, len(leaves), MID):
        nm = f"M{g // MID}"
        mids.append(nm)
        out.append(f"def {nm} : List (List Nat) := [{', '.join(leaves[g:g + MID])}]\n")
    out.append("def ROOT : List (List (List Nat)) := [" + ", ".join(mids) + "]\n")
    out.append(f"""
/-- The table read: `kT k` is the author's kernel-table entry `k` (0 out of range). -/
def kT (k : Nat) : Nat :=
  (ROOT.getD (k / {SPAN}) []).getD ((k % {SPAN}) / {LEAF}) [] |>.getD (k % {LEAF}) 0

end Cert
""")
    return "".join(out)

if __name__ == "__main__":
    assert hashlib.sha256(BIN.read_bytes()).hexdigest() == SHA
    p = PLAY / "cert" / "Table.lean"
    p.write_text(gen())
    print(p, p.stat().st_size, "bytes")
