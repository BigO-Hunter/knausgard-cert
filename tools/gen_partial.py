#!/usr/bin/env python3
"""Emit cert/Partial.lean: the Axiom-1 partial-coverage certificate.

One kernel-checked theorem, `covered_pass`, states that every covered box passes the author's own
range-minimum test `basicF` on the author's own kernel table (read through our tree accessor `kT`).
Plus per-box theorems for the first few boxes, so a single leaf can be read and re-checked alone.

Usage: python3 gen_partial.py <selection.json> <out.lean> [n_exemplars]
"""
import json, sys
from pathlib import Path

sel = json.loads(Path(sys.argv[1]).read_text())
out = Path(sys.argv[2])
nex = int(sys.argv[3]) if len(sys.argv) > 3 else 8
boxes = sel["chosen"]
fv = sel["covered_fraction"]


def arr(xs):
    """Array literal, for basicF's arguments."""
    return "#[" + ", ".join(map(str, xs)) + "]"


def larr(xs):
    """List literal, for the `covered` list (a List, not an Array)."""
    return "[" + ", ".join(map(str, xs)) + "]"


head = f"""-- Cert/Partial.lean  (generated by tools/gen_partial.py -- do not hand-edit)
--
-- AXIOM 1 PARTIAL-COVERAGE CERTIFICATE for arXiv:2610.08965 (Kristian Muri Knausgård),
-- development Distinct839, upstream commit b280d51bef5ab32b3280b0955d040085ed522d59.
--
-- WHAT IS CLAIMED.  `covered_pass` is a kernel-checked theorem: every box in `covered` passes the
-- author's own range-minimum test `basicF`, evaluated by the Lean KERNEL (`by decide +kernel`), on
-- the author's own kernel table (209010 entries, sha256
-- b80e5a8c70e4beb3b872dada426016bc97b0954c1a8a5eabaeb40fba49cded36) read through the accessor
-- `Cert.kT`.  By his `basicF_sound` (Distinct839/Local/Spot.lean, unmodified, general in the box)
-- each of these boxes therefore satisfies `BoxOK`, i.e. the local inequality holds on it.
--
-- WHAT IS NOT CLAIMED.  This does NOT discharge Axiom 1.  The covered boxes are {len(boxes)} of the
-- 30,233,655 accepted boxes of his search, and they cover {fv:.3e} of the volume of the root box
-- [13926,209009]^6 (exact integer volume {sel['covered_volume']} of {sel['root_volume']}).
-- Everything else is still the single trusted compiled boolean he records as
-- `Distinct839.Local.check_passes._native.native_decide.ax_1_1`.  See COVERAGE.md.
--
-- WHERE THE BOXES COME FROM.  From his reference verifier `verifier/verify.cpp` (untrusted here:
-- it is only a candidate generator), instrumented by tools/patch_dump.py to report its accepted
-- boxes; its counts on the stock build reproduce certificate/cpp_verification.json exactly
-- (nodes 60467309, leaves 30233655, basic 21157274, affine 9076381).  The boxes below are the
-- accepted ones with the largest volume per kernel read, i.e. the cheapest coverage first; the
-- selection is in cert/{Path(sys.argv[1]).name} and the generator is tools/select_leaves.py.
--
-- BUDGET.  {sel['used_reads']} table reads (`basicF` reads gap r exactly (r+1)(6-r) times per box,
-- 56 reads per unit width in all six gaps), chosen to fit a fixed kernel budget; see BENCHMARK.md
-- for the measured cost per read on this machine.
import Defs
import Table

set_option maxHeartbeats 0
set_option maxRecDepth 1000000

namespace Cert

open Distinct839.Local

/-- The covered boxes: (lower corner, upper corner), gaps in units of 1/16384. -/
def covered : List (List Nat × List Nat) := [
"""

body = "".join("  (%s, %s),\n" % (larr(b["lo"]), larr(b["hi"])) for b in boxes)

tail = f"""]
/-- **The certificate**: every covered box passes the range-minimum test — kernel-checked. -/
theorem covered_pass : covered.all (fun p => basicF kT p.1.toArray p.2.toArray) = true := by
  decide +kernel

instance : Inhabited (List Nat × List Nat) := ⟨([], [])⟩

section Exemplars
/-! The first {nex} covered boxes, each checked on its own line, so that a reader can copy one
line out and re-check a single leaf in isolation. -/

"""

ex = []
for k, b in enumerate(boxes[:nex]):
    ex.append(f"theorem covered_{k} : basicF kT {arr(b['lo'])} {arr(b['hi'])} = true := by decide +kernel\n")

tail2 = f"""
end Exemplars

end Cert
"""
out.write_text(head + body + tail + "".join(ex) + tail2)
print(f"wrote {out} ({out.stat().st_size} bytes, {len(boxes)} boxes, {nex} exemplars)")
